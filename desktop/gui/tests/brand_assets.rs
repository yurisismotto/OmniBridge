// ===========================================================================
// PLIWEE-W7 — the desktop artwork derives from the Pliwee masters
// ===========================================================================
//
// Wave 7 moves the desktop off the OmniBridge artwork. The brand mark is the
// frozen master itself, compiled in; the application icon is a placement of
// that master on the 512-unit grid, produced by
// `docs/reports/branding/pliwee-wave-7/derive_desktop_app_icon.py`. These
// re-prove the derivation from the files, so a hand edit to the icon, or a
// build that quietly goes back to the old artwork, fails here.

/// The block between `<defs>` and `</defs>`, inclusive.
fn defs_block(svg: &str) -> &str {
    let start = svg.find("<defs>").expect("a <defs> block");
    let end = svg.rfind("</defs>").expect("a closing </defs>") + "</defs>".len();
    &svg[start..end]
}

/// The icon is the master's artwork, copied byte for byte, drawn once.
///
/// Byte equality of the whole `<defs>` block covers the four paths, the clip,
/// every gradient stop and the `mark` symbol's own viewBox and paint order —
/// there is nothing in the icon's artwork that the master did not supply.
/// What follows the defs is one `<use>` of that symbol, square and on the
/// 512-unit grid, so the symbol's own viewBox and the default
/// `preserveAspectRatio` scale it uniformly: nothing is stretched.
#[test]
fn the_desktop_app_icon_is_a_placement_of_the_pliwee_master() {
    let master = read("pliwee-mark.svg");
    let icon = read("pliwee-app-icon.svg");

    let master_defs = defs_block(&master);
    assert!(
        master_defs.len() > 20_000,
        "the master's defs are implausibly short ({} bytes), so equality would prove little",
        master_defs.len()
    );
    assert_eq!(
        defs_block(&icon),
        master_defs,
        "pliwee-app-icon.svg's artwork is not the master's, byte for byte"
    );
    assert_eq!(attr(&icon, "viewBox").as_deref(), Some("0 0 512 512"));

    let drawn = icon
        .rsplit_once("</defs>")
        .expect("content after the defs")
        .1;
    assert_eq!(
        drawn.trim(),
        "<use href=\"#mark\" x=\"50\" y=\"50\" width=\"412\" height=\"412\"/></svg>",
        "the icon draws something other than one square placement of the mark"
    );
    assert!(
        !icon.contains("preserveAspectRatio"),
        "the mark must not be stretched"
    );

    let lower = icon.to_lowercase();
    for dead in [
        "anyflow",
        "flow a",
        "flow-a",
        "flow_a",
        "flowing",
        "fedroid",
        "omnibridge",
        "one bridge",
    ] {
        assert!(
            !lower.contains(dead),
            "pliwee-app-icon.svg carries {dead:?}"
        );
    }
}

