//! Structural validation of the OmniBridge brand artwork.
//!
//! The marks are source-controlled vectors that get compiled into the binary
//! and shipped as the application icon, so what can go wrong with them is not
//! "it looks off" — it is that an asset quietly starts depending on something
//! that will not be there:
//!
//! * an embedded raster, which stops it being a vector at all;
//! * a network reference, which a desktop icon must never make;
//! * a bundled or named font, which a person's machine may not have and which
//!   the typography decision forbids shipping;
//! * a filesystem path left behind by an editor, which leaks whose machine it
//!   was drawn on;
//! * a stroke so fine that the mark disappears at 16 px, which is the one
//!   size an application icon is guaranteed to be drawn at.
//!
//! None of that is visible by looking at the picture, which is why it is
//! checked here. How the marks *look* at each size is a human judgement and
//! is recorded in the sprint report instead.
//!
//! This is a GUI-crate test target on purpose. It reads desktop artwork and
//! is not part of the portable core, so it is outside the boundary
//! `portable-windows-msvc.yml` measures — that job's classification guards
//! watch `core/tests` and `capabilities/notifications/tests`, and neither is
//! this.

use std::path::{Path, PathBuf};

/// The canonical asset directory, relative to this crate.
fn assets() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/design/assets")
}

/// The OmniBridge artwork this application shipped until rebrand Wave 7.
///
/// Named one by one rather than globbed: a new asset should have to state that
/// it exists, and an asset that is deleted should fail here rather than stop
/// being checked silently.
///
/// Nothing compiles or installs these any more: since Wave 7 the desktop draws
/// the Pliwee masters and `pliwee-app-icon.svg` (the tests at the end of this
/// file). They stay in the tree, and stay checked, until they are retired.
/// All six are the approved OmniBridge artwork, as it was installed verbatim. None is
/// redrawn, retraced or regenerated by this repository, which is why the tests
/// below check *relationships between* them rather than second-guessing their
/// shapes.
const ASSETS: [&str; 6] = [
    "omnibridge-mark.svg",
    "omnibridge-mark-mono.svg",
    "omnibridge-app-icon.svg",
    "omnibridge-android-monochrome.svg",
    "omnibridge-wordmark.svg",
    "omnibridge-logo-lockup.svg",
];

/// The assets that are not the canonical mark but must be built out of it.
///
/// The wordmark is excluded on purpose: it is letterforms, not the symbol, and
/// carries none of the mark's geometry.
const DERIVED_FROM_THE_MARK: [&str; 4] = [
    "omnibridge-mark-mono.svg",
    "omnibridge-app-icon.svg",
    "omnibridge-android-monochrome.svg",
    "omnibridge-logo-lockup.svg",
];

fn read(name: &str) -> String {
    let path = assets().join(name);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{} is missing: {e}", path.display()))
}

/// Pulls an attribute off the first element that carries it.
///
/// Matched on a whole attribute name, not a substring: `d="` also occurs
/// inside `id="`, and a scanner that does not care about the boundary reads a
/// gradient's name as a path's geometry.
fn attr(svg: &str, name: &str) -> Option<String> {
    let needle = format!("{name}=\"");
    svg.match_indices(&needle)
        .find(|(index, _)| {
            *index == 0
                || svg[..*index]
                    .chars()
                    .next_back()
                    .is_some_and(|c| c.is_whitespace() || c == '<')
        })
        .and_then(|(index, _)| svg[index + needle.len()..].split('"').next())
        .map(str::to_string)
}

/// The canonical symbol's outline, read out of the canonical file.
///
/// This one string is what every other asset has to agree with, and it is
/// taken from the artwork rather than written down here — a constant copied
/// into this file would only prove that the constant matches itself.
fn canonical_silhouette() -> String {
    const OPEN: &str = "<clipPath id=\"clip\"><path d=\"";
    let svg = read("omnibridge-mark.svg");
    let at = svg
        .find(OPEN)
        .expect("the canonical mark defines its outline as a clip path");
    svg[at + OPEN.len()..]
        .split('"')
        .next()
        .expect("the outline is a quoted attribute")
        .to_string()
}

#[test]
fn every_asset_is_a_self_contained_svg() {
    for name in ASSETS {
        let svg = read(name);
        assert!(
            svg.contains("<svg") && svg.trim_end().ends_with("</svg>"),
            "{name} is not an SVG document"
        );
        assert!(
            svg.contains("xmlns=\"http://www.w3.org/2000/svg\""),
            "{name} does not declare the SVG namespace"
        );
        // Without a viewBox the mark does not scale, which is the entire
        // reason it is a vector.
        assert!(attr(&svg, "viewBox").is_some(), "{name} has no viewBox");
        assert_eq!(
            svg.matches("<svg").count(),
            1,
            "{name} has more than one root"
        );
    }
}

/// Nothing is fetched, embedded or inherited from outside the file.
///
/// `<use href="#…">` is *not* forbidden, and that is the one interesting line
/// here. The approved artwork composes itself out of a `<symbol>` it defines
/// a few lines earlier, which is a same-document reference and stays valid
/// wherever the file is opened. What must never appear is a reference that
/// leaves the document.
#[test]
fn no_asset_reaches_outside_itself() {
    for name in ASSETS {
        let svg = read(name);
        let lower = svg.to_lowercase();

        for forbidden in [
            "<image",     // an embedded or linked raster
            "data:image", // a raster smuggled in as a data URI
            "<script",    // an icon is not a program
            "@font-face", // a bundled font
            "<font",
            ".ttf",
            ".woff",
            "<text", // text in a mark is a font dependency by another name
            "font-family",
        ] {
            assert!(
                !lower.contains(forbidden),
                "{name} contains {forbidden:?}, which makes it depend on something outside itself"
            );
        }

        // Every reference stays inside this document.
        for (index, _) in lower.match_indices("href=\"") {
            let target: String = lower[index + 6..]
                .chars()
                .take_while(|c| *c != '"')
                .collect();
            assert!(
                target.starts_with('#'),
                "{name} references {target:?}, which is outside the file"
            );
        }

        // The namespace declaration is a URI, not a fetch. Any *other* http
        // reference would be.
        let http_uses: Vec<&str> = lower
            .match_indices("http")
            .map(|(i, _)| &lower[i..(i + 40).min(lower.len())])
            .filter(|s| !s.starts_with("http://www.w3.org/2000/svg"))
            .collect();
        assert!(
            http_uses.is_empty(),
            "{name} references the network: {http_uses:?}"
        );

        // An editor that wrote out where it was run leaks the author's
        // machine into a file that ships.
        for leak in [
            "/home/",
            "/users/",
            "file://",
            "c:\\",
            "sodipodi",
            "inkscape:",
        ] {
            assert!(
                !lower.contains(leak),
                "{name} leaks a local path or editor state: {leak:?}"
            );
        }
    }
}

/// Every gradient a mark paints with is defined in that same mark.
///
/// A `url(#id)` that resolves to nothing does not fail loudly — the shape is
/// simply painted black, or not at all, which is exactly the kind of breakage
/// that reaches a release.
#[test]
fn every_paint_reference_resolves_inside_its_own_file() {
    for name in ASSETS {
        let svg = read(name);
        for (index, _) in svg.match_indices("url(#") {
            let id: String = svg[index + 5..].chars().take_while(|c| *c != ')').collect();
            assert!(
                svg.contains(&format!("id=\"{id}\"")),
                "{name} paints with url(#{id}), which it never defines"
            );
        }
    }
}

/// An id is unique within the file that defines it.
///
/// Scoped per file, not across the family, and the difference is the point.
/// The approved assets all define `base`, `front`, `shadow` and `clip`,
/// because each is a standalone document carrying its own copy of the artwork
/// — that is what makes them independently openable. A collision only matters
/// *inside* one document, where the second definition silently wins.
#[test]
fn gradient_ids_are_unique_within_each_file() {
    for name in ASSETS {
        let svg = read(name);
        let mut seen: Vec<String> = Vec::new();
        for (index, _) in svg.match_indices("id=\"") {
            let id: String = svg[index + 4..].chars().take_while(|c| *c != '"').collect();
            assert!(!seen.contains(&id), "{name} defines id {id:?} twice");
            seen.push(id);
        }
    }
}

/// Every derived asset carries the canonical outline, byte for byte.
///
/// This is the assertion the whole sprint rests on, and it is deliberately
/// made on geometry rather than on filenames: a file called
/// `omnibridge-app-icon.svg` that drew something else would pass a name check
/// and fail this one. The outline is thousands of characters of coordinates,
/// so an equality here is not a coincidence — it is the same artwork.
#[test]
fn every_derived_asset_carries_the_canonical_geometry() {
    let canonical = canonical_silhouette();
    assert!(
        canonical.len() > 2000,
        "the canonical outline is implausibly short ({} chars), so this test is \
         not proving what it claims",
        canonical.len()
    );
    for name in DERIVED_FROM_THE_MARK {
        let svg = read(name);
        assert!(
            svg.contains(&canonical),
            "{name} does not carry the canonical outline from omnibridge-mark.svg"
        );
    }
}

